extern crate isla_lib;
use isla_lib::bitvector::b64::B64;
use isla_lib::bitvector::BV;
use isla_lib::ir::{BitsSegment, Name, Val};
use isla_lib::smt::{self, checkpoint, Config, Context, Event, SmtResult, Solver};
use isla_lib::smt::smtlib::{self, Def, Exp, Ty};
use isla_lib::source_loc::SourceLoc;
fn main() {
    smt::configure_tastic(smt::Tactic::Qfaufbv);
    let loc=SourceLoc::unknown();
    let original_ctx=Context::new(Config::new());
    let mut s=Solver::<B64>::new(&original_ctx);
    let state=s.declare_const(Ty::Bool,loc);
    let field=s.declare_const(Ty::BitVec(8),loc);
    let tag=s.declare_const(Ty::BitVec(32),loc);
    let en=s.get_enum(Name::from_u32(900),2);
    let enum_field=s.declare_const(Ty::Enum(en),loc);
    let state_alias=s.define_const(Exp::Var(state),loc);
    let predicate=s.define_const(Exp::Eq(Box::new(Exp::Var(field)),Box::new(smtlib::bits64(1,8))),loc);
    let chained=s.define_const(Exp::And(Box::new(Exp::Var(predicate)),Box::new(Exp::Eq(Box::new(Exp::Var(enum_field)),Box::new(Exp::Enum(en.first_member()))))),loc);
    let mixed=s.define_const(Exp::And(Box::new(Exp::Var(chained)),Box::new(Exp::Var(state))),loc);
    let function=s.fresh();s.add(Def::DeclareFun(function,vec![],Ty::Bool));
    let ground_app=s.define_const(Exp::App(function,vec![]),loc);
    s.assert(Exp::Var(chained));
    s.assert_eq(Exp::Var(tag),smtlib::bits64(901,32));
    s.assert(Exp::Var(state));s.assert(Exp::Var(state_alias));
    s.assert(Exp::Var(mixed));s.assert(Exp::Var(ground_app));s.assert(Exp::Bool(true));
    s.trace_call(Name::from_u32(902));
    let full=checkpoint(&mut s);
    let original_events=full.trace().as_ref().unwrap().to_vec();
    let original_text:Vec<_>=original_events.iter().map(|event|format!("{:?}",event)).collect();
    let payload=Val::MixedBits(vec![BitsSegment::Concrete(B64::new(0,1)),BitsSegment::Symbolic(field)]);
    let symbolic_ctor=Val::SymbolicCtor(tag,[(Name::from_u32(901),payload)].into_iter().collect());
    let instruction=Val::Struct([(Name::from_u32(903),symbolic_ctor),(Name::from_u32(904),Val::Vector(vec![Val::Symbolic(enum_field),Val::Symbolic(state_alias)]))].into_iter().collect());
    let isolated=full.with_instruction_assertions(&instruction);
    let isolated_events=isolated.trace().as_ref().unwrap().to_vec();
    let original_nonassert:Vec<_>=original_events.iter().filter(|event|!matches!(event,Event::Smt(Def::Assert(_),_,_))).map(|event|format!("{:?}",event)).collect();
    let isolated_nonassert:Vec<_>=isolated_events.iter().filter(|event|!matches!(event,Event::Smt(Def::Assert(_),_,_))).map(|event|format!("{:?}",event)).collect();
    assert_eq!(original_nonassert,isolated_nonassert);
    let kept=isolated_events.iter().filter(|event|matches!(event,Event::Smt(Def::Assert(_),_,_))).count();assert_eq!(kept,3);
    assert_eq!(original_text,full.trace().as_ref().unwrap().to_vec().iter().map(|event|format!("{:?}",event)).collect::<Vec<_>>());
    let helper_ctx=Context::new(Config::new());let mut helper=Solver::from_checkpoint(&helper_ctx,isolated.clone());
    assert_eq!(helper.check_sat(loc),SmtResult::Sat);
    assert_eq!(helper.check_sat_with(&Exp::Not(Box::new(Exp::Var(state))),loc),SmtResult::Sat);
    assert_eq!(helper.check_sat_with(&Exp::Not(Box::new(Exp::Var(state_alias))),loc),SmtResult::Sat);
    assert_eq!(helper.check_sat_with(&Exp::Not(Box::new(Exp::Var(ground_app))),loc),SmtResult::Sat);
    assert_eq!(helper.check_sat_with(&Exp::Not(Box::new(Exp::Var(predicate))),loc),SmtResult::Unsat);
    assert_eq!(helper.check_sat_with(&Exp::Not(Box::new(Exp::Var(chained))),loc),SmtResult::Unsat);
    helper.assert(Exp::Not(Box::new(Exp::Var(state))));
    let combined=full.with_suffix_from(&isolated,&checkpoint(&mut helper));
    let final_ctx=Context::new(Config::new());let mut final_solver=Solver::from_checkpoint(&final_ctx,combined);
    assert_eq!(final_solver.check_sat(loc),SmtResult::Unsat);
    println!("PASS: 嵌套Struct/Vector、MixedBits字段、SymbolicCtor tag、枚举、两级定义、派生状态输入、ground App、原事件/表达式不变、完整约束恢复");
}
